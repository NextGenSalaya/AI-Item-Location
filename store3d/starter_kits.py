def needs_for(name: str, mode: str = "new"):
    """All needs of a kit (with the common supplies / equipment), filtered for the mode:
    "new" = opening a new shop (everything), "restock" = an existing shop topping up (no equipment)."""
    kit = KITS[name]
    needs = list(kit["needs"])
    if kit.get("common", True):
        have = {n[1] for n in needs}
        needs += [n for n in COMMON_SUPPLY + COMMON_EQUIP if n[1] not in have]
    if mode == "restock":
        needs = [n for n in needs if n[0] != "equip"]
    return needs


def pick_kit(request: str):
    """Kit named in the request (e.g. "ร้านข้าวแกง"), else the kit whose keywords appear (longest wins), else None."""
    named = [n for n in KITS if n in request or n.replace("ร้าน", "", 1) in request]
    if named:
        return max(named, key=len)
    best, best_len = None, 0
    for name, kit in KITS.items():
        for kw in kit["match"]:
            if kw in request and len(kw) > best_len:
                best, best_len = name, len(kw)
    return best

